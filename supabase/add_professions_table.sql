-- Lista de profissões do menu suspenso com pesquisa (FloatingSearchSelect).
--
-- Editada direto no Supabase (Table Editor), sem deploy: para incluir uma
-- profissão basta inserir uma linha; para tirá-la do menu sem apagar, marque
-- active = false. O backend lê com a chave de serviço, então o RLS fica
-- fechado para o acesso público, como nas demais tabelas.

create table if not exists public.professions (
  id bigint generated always as identity primary key,
  name text not null,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Evita duplicadas que só diferem em maiúsculas/minúsculas ("Médico" x "médico").
create unique index if not exists professions_name_lower_idx
  on public.professions (lower(name));

alter table public.professions enable row level security;

comment on table public.professions is 'Opções do menu de profissões. active = false esconde a opção sem apagá-la.';

